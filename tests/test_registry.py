    def test_create_model_from_registry(self):
        model = create_model(
            "Informer",
            domain="forecasting",
            enc_in=1,
            dec_in=1,
            c_out=1,
            seq_len=16,
            label_len=8,
            pred_len=4,
        )
        self.assertEqual(model.__class__.__name__, "Informer")
        self.assertGreater(model.param_count(), 0)
        self.assertEqual(torch_like.__version__, "0.2.0")

    def test_config_roundtrip_preserves_model_specific_arguments(self):
        model = torch_like.GAT(
            input_dim=3,
            output_dim=2,
            num_nodes=5,
            d_model=8,
            num_layers=3,
            heads=2,
        )
        restored = torch_like.GAT.from_config(model.config())
        self.assertEqual(model.config()["num_layers"], 3)
        self.assertEqual(model.config()["heads"], 2)
        self.assertEqual(model.param_count(), restored.param_count())

    def test_flat_registry_has_no_domain_collisions(self):
        by_domain_count = sum(len(torch_like.model_zoo[domain]) for domain in torch_like.model_zoo)
        self.assertEqual(len(list_models()), by_domain_count)
        self.assertNotIn("InformerRUL", list_models("forecasting"))
        self.assertIn("InformerRUL", list_models("rul"))

