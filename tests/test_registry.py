class RegistryTests(unittest.TestCase):
    def test_registry_domain_and_metadata_contract(self):
        expected_fields = {
            "cls",
            "family",
            "layer",
            "integration_level",
            "supports",
            "paper",
            "description",
            "complexity",
            "automl_default",
        }
        self.assertEqual(list_domains(), tuple(torch_like.model_zoo))
        for domain in list_domains():
            for metadata in list_models(domain).values():
                self.assertEqual(set(metadata), expected_fields)
                self.assertIsInstance(metadata["automl_default"], bool)
                self.assertIsInstance(metadata["cls"], type)
                self.assertTrue(all(isinstance(tag, str) and tag for tag in metadata["supports"]))

    def test_registry_metadata_queries_are_defensive_copies(self):
        info = get_model_info("PatchTST", domain="forecasting")
        info["supports"].append("local-only")
        self.assertNotIn("local-only", get_model_info("PatchTST", domain="forecasting")["supports"])

    def test_registry_rejects_unknown_domains(self):
        with self.assertRaisesRegex(KeyError, "Unknown model domain"):
            list_models("missing-domain")

    def test_catalog_registration_is_atomic(self):
        domain = "__invalid_catalog_test__"
        with self.assertRaisesRegex(ValueError, "Missing model metadata fields"):
            register_model_catalog(domain, {"Invalid": {"cls": object, "family": "test"}})
        self.assertNotIn(domain, torch_like.model_zoo)

    def test_top_level_exports_follow_model_exports(self):
        registry_exports = {
            "__version__",
            "model_zoo",
            "list_domains",
            "list_models",
            "list_models_by_support",
            "list_models_by_family",
            "get_model_info",
            "create_model",
        }
        self.assertEqual(len(torch_like.__all__), len(set(torch_like.__all__)))
        self.assertEqual(set(torch_like.__all__) - registry_exports, set(model_package.MODEL_EXPORTS))

    def test_registry_rejects_duplicate_and_cross_domain_names(self):
        class FirstModel:
            pass

        class SecondModel:
            pass

        name = "__RegistryCollisionTest__"
        try:
            register_model("diagnosis", name, FirstModel, family="test")
            self.assertIs(register_model("diagnosis", name, FirstModel, family="test"), FirstModel)
            with self.assertRaisesRegex(ValueError, "already registered"):
                register_model("diagnosis", name, SecondModel, family="test")
            with self.assertRaisesRegex(ValueError, "globally unique"):
                register_model("graph", name, FirstModel, family="test")
        finally:
            torch_like.model_zoo["diagnosis"].pop(name, None)

