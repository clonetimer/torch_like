    def test_registry_support_and_family_queries(self):
        graph_models = list_models_by_support("graph_mode", domain="forecasting")
        self.assertIn("MTGNN", graph_models)
        self.assertIn("GraphWaveNet", graph_models)
        self.assertIn("AGCRN", graph_models)
        self.assertIn("D2STGNN", graph_models)
        self.assertNotIn("PatchTST", graph_models)

        exog_models = list_models_by_support("exogenous", domain="forecasting")
        self.assertIn("TimeXer", exog_models)
        self.assertIn("TFT", exog_models)
        self.assertIn("DAG", exog_models)
        self.assertIn("TiDE", exog_models)

        dynamics_models = list_models_by_family("dynamical_systems", domain="forecasting")
        self.assertIn("Koopa", dynamics_models)

        frequency_models = list_models_by_family("frequency_domain", domain="forecasting")
        self.assertIn("FreTS", frequency_models)

        transformer_models = list_models_by_family("transformer_attention", domain="forecasting")
        self.assertIn("PatchTST", transformer_models)
        self.assertIn("AST", transformer_models)
        self.assertIn("Informer", transformer_models)
        self.assertNotIn("MTGNN", transformer_models)

        probabilistic_models = list_models_by_support("sampling", domain="forecasting")
        self.assertIn("DeepAR", probabilistic_models)
        self.assertIn("TimeGrad", probabilistic_models)
        self.assertIn("ProTran", probabilistic_models)
        self.assertIn("PPM", probabilistic_models)

