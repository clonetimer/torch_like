"""Frozen USAD/TranAD parity against original AAS Phase 9 implementations.

Original archive SHA-256:
86d3134dbe73ba6e9f361cb1dac45fccaaeb2d56f10928a9679999ce485ad8cf
Original source: AAS/detectors/torch_like_neural.py

Reference scores and losses were generated by running the exact AAS
_USADModel/_TranADModel at PyTorch 2.10.0+cpu. The test fills *all*
parameters deterministically based on canonical state_dict names and
compares equivalent upstream models, not two independent random initializations.
"""

from __future__ import annotations

import unittest

import numpy as np
import torch

from torch_like.models.detection.common import DetectionBatch
from torch_like.models.detection.tranad import TranAD
from torch_like.models.detection.usad import USAD

_AAS_USAD = {
    "scores": [0.3888019025325775, 0.01327318325638771, 0.15932534635066986, 0.8264005184173584],
    "loss": 0.8450352549552917,
    "state_keys": 12,
}
_AAS_TRANAD = {
    "scores": [0.33248069882392883, 0.004512022715061903, 0.19804657995700836, 0.913084089756012],
    "loss": 0.34649497270584106,
    "state_keys": 19,
}


def _fill_by_canonical_name(model):
    """AAS->upstream USAD decoder prefix was normalized before golden generation."""
    with torch.no_grad():
        for name, parameter in model.named_parameters():
            shift = ((sum(name.encode("utf-8")) % 17) - 8) * 0.0002
            values = torch.linspace(
                -0.05, 0.05, parameter.numel(), dtype=parameter.dtype, device=parameter.device
            ).reshape_as(parameter)
            parameter.copy_(values + shift)
    model.eval()


class NeuralAASPhase9FrozenParityTests(unittest.TestCase):
    def test_usad_and_tranad_mapped_weight_parity_with_original_aas(self):
        x = torch.linspace(-1, 1, 48, dtype=torch.float32).reshape(4, 4, 3)
        cases = (
            ("USAD", USAD(input_dim=3, seq_len=4, hidden_dim=12, latent_dim=5, dropout=0.0, alpha=0.45), _AAS_USAD),
            (
                "TranAD",
                TranAD(input_dim=3, seq_len=4, d_model=8, n_heads=2, e_layers=1, d_ff=16, dropout=0.0),
                _AAS_TRANAD,
            ),
        )
        for name, model, golden in cases:
            with self.subTest(model=name):
                _fill_by_canonical_name(model)
                self.assertEqual(len(model.state_dict()), golden["state_keys"])
                with torch.inference_mode():
                    actual_scores = model.score_batch(DetectionBatch(x)).detach().cpu().numpy()
                    actual_loss = float(model.fit_step(DetectionBatch(x)).item())
                np.testing.assert_allclose(actual_scores, golden["scores"], rtol=2e-5, atol=2e-6)
                np.testing.assert_allclose([actual_loss], [golden["loss"]], rtol=2e-5, atol=2e-6)

    def test_usad_decoder_key_remapping_is_explicit_and_lossless(self):
        model = USAD(input_dim=3, seq_len=4, hidden_dim=12, latent_dim=5, dropout=0.0, alpha=0.45)
        upstream = model.state_dict()
        aas_style = {}
        for key, tensor in upstream.items():
            name = key
            for decoder in ("decoder_1.", "decoder_2."):
                if key.startswith(decoder + "net."):
                    name = decoder + key[len(decoder + "net.") :]
                    break
            self.assertNotIn(name, aas_style)
            aas_style[name] = tensor.clone()
        self.assertIn("decoder_1.0.weight", aas_style)
        self.assertIn("decoder_2.3.bias", aas_style)
        self.assertNotIn("decoder_1.net.0.weight", aas_style)
        mapped = {}
        for key, tensor in aas_style.items():
            if key.startswith(("decoder_1.", "decoder_2.")):
                decoder, suffix = key.split(".", 1)
                new_key = f"{decoder}.net.{suffix}"
            else:
                new_key = key
            self.assertNotIn(new_key, mapped)
            mapped[new_key] = tensor
        self.assertEqual(set(mapped), set(upstream))
        self.assertEqual(
            {key: tuple(value.shape) for key, value in mapped.items()},
            {key: tuple(value.shape) for key, value in upstream.items()},
        )
        model.load_state_dict(mapped, strict=True)


if __name__ == "__main__":
    unittest.main()
