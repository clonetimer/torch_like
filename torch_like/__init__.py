def __getattr__(name: str):
    if name in {"model_zoo", "list_models", "list_models_by_support", "list_models_by_family", "create_model"}:
        return globals()[name]
    models_module = import_module("torch_like.models")
    return getattr(models_module, name)


def __dir__():
    return sorted(set(globals()) | set(__all__))
